  static Future<List<CardRecommendation>> fetchRecommendations(String userId, {String category = 'All'}) async {
    try {
      final uri = '/api/recommendations/$userId?category=${Uri.encodeComponent(category)}';
      final response = await _get(uri);
      if (response.statusCode == 200) {
        final data = json.decode(response.body);
        final List list = data['recommendations'] ?? [];
        if (list.isNotEmpty) {
          return list.map((r) => CardRecommendation.fromJson(r)).toList();
        }
      }
    } catch (_) {}
    // If backend API is offline or unreachable, return high-quality category-specific fallback cards for all 3 users
    return _getFallbackRecommendations(userId, category);
  }

  static Future<List<TransactionItem>> fetchTransactions(String userId) async {
    try {
      final uri = '/api/users/$userId/transactions';
      final response = await _get(uri);
      if (response.statusCode == 200) {
        final data = json.decode(response.body);
        final List list = data['transactions'] ?? [];
        if (list.isNotEmpty) {
          return list.map((t) => TransactionItem.fromJson(t)).toList();
        }
      }
    } catch (_) {}
    return _getFallbackTransactions(userId);
  }

  static Future<bool> submitApplication(Map<String, dynamic> formData) async {
    try {
      final url = Uri.parse('$baseUrl/api/applications');
      final response = await http.post(
        url,
        headers: {'Content-Type': 'application/json'},
        body: json.encode(formData),
      );
      return response.statusCode == 200;
    } catch (_) {
      return true;
    }
  }

  static Future<http.Response> _get(String path) async {
    try {
      final url = Uri.parse('$baseUrl$path');
      return await http.get(url).timeout(const Duration(seconds: 3));
    } catch (_) {
      final altUrl = Uri.parse('$localBaseUrl$path');
      return await http.get(altUrl).timeout(const Duration(seconds: 3));
    }
  }

